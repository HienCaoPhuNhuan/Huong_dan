const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const assert = require('node:assert/strict');
const {chromium} = require('playwright');
const root = path.resolve(__dirname, '..');
const server = http.createServer((req, res) => {
  const name = decodeURIComponent(new URL(req.url, 'http://localhost').pathname);
  const file = path.resolve(root, '.' + (name === '/' ? '/index.html' : name));
  if (!file.startsWith(root + path.sep) || !fs.existsSync(file)) { res.writeHead(404); res.end(); return; }
  const types = {'.html':'text/html; charset=utf-8','.css':'text/css','.js':'text/javascript','.svg':'image/svg+xml','.wasm':'application/wasm'};
  res.setHeader('Content-Type', types[path.extname(file)] || 'application/octet-stream');
  fs.createReadStream(file).pipe(res);
});
let browser;
(async () => {
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  browser = await chromium.launch({headless:true,channel:'chrome'});
  const base = 'http://127.0.0.1:' + server.address().port;
  const page = await browser.newPage({viewport:{width:1440,height:900}});
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  for (const lesson of require('../curriculum.json')) {
    await page.goto(base + '/' + lesson.file);
    await page.waitForSelector('.reader-toolbar');
    assert.ok(await page.locator('.reading-anchor').count(), lesson.file);
    assert.equal(await page.locator('.lesson-nav:visible').count(), 0);
    assert.equal(await page.evaluate(() => getComputedStyle(document.documentElement).scrollSnapType), 'y');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, lesson.file);
    await page.getByRole('button',{name:'Mở mục lục bài',exact:true}).click();
    assert.equal(await page.locator('dialog[open]').count(), 1);
    await page.keyboard.press('Escape');
    assert.equal(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), 'Mở mục lục bài');
  }
  await page.goto(base + '/tai-khoan-chatgpt.html');
  assert.equal(await page.locator('#signup p').first().evaluate(e => getComputedStyle(e).textAlign), 'justify');
  await page.getByRole('button',{name:'Phần tiếp theo',exact:true}).click();
  await page.waitForTimeout(1200);
  assert.ok(Math.abs(await page.locator('.reading-anchor').nth(1).evaluate(e => e.getBoundingClientRect().top) - 88) < 8);
  const before = await page.evaluate(() => scrollY);
  await page.mouse.move(1200,700); await page.mouse.wheel(0,160);
  await page.waitForTimeout(800);
  assert.ok(await page.evaluate(() => scrollY) >= before, 'Native wheel remains available');
  await page.screenshot({path:path.join(root,'qa-output/reader-focused.png')});
  await page.locator('.chapter-actions a').last().click();
  assert.ok(await page.evaluate(() => document.documentElement.classList.contains('route-leaving')));
  await page.waitForTimeout(380);
  await page.screenshot({path:path.join(root,'qa-output/reader-transition.png')});
  await page.waitForURL('**/thiet-lap-github.html');
  await page.waitForTimeout(1000);
  assert.equal(await page.evaluate(() => /route-(leaving|arriving)/.test(document.documentElement.className)), false);
  await page.goBack(); await page.waitForTimeout(250);
  assert.equal(await page.evaluate(() => document.documentElement.classList.contains('route-leaving')), false);
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto(base + '/tai-khoan-chatgpt.html');
  assert.equal(await page.evaluate(() => getComputedStyle(document.documentElement).scrollSnapType), 'none');
  await page.locator('.chapter-actions a').last().click(); await page.waitForURL('**/thiet-lap-github.html');
  assert.equal(await page.evaluate(() => document.documentElement.classList.contains('route-arriving')), false);
  await page.goto(base + '/ke-chuyen-thi-giac.html');
  const scroller = page.locator('.story-scroller');
  await scroller.scrollIntoViewIfNeeded();
  const box = await scroller.boundingBox();
  await page.mouse.move(box.x + box.width/2, box.y + Math.min(box.height/2,200));
  await page.mouse.wheel(0,250); await page.waitForTimeout(500);
  assert.ok(await scroller.evaluate(e => e.scrollTop) > 0, 'Nested demo remains independently scrollable');
  const fallback = await browser.newPage({javaScriptEnabled:false});
  await fallback.goto(base + '/tai-khoan-chatgpt.html');
  assert.equal(await fallback.locator('.lesson-nav:visible').count(), 1);
  await fallback.close();
  const blocked = await browser.newPage();
  await blocked.addInitScript(() => { Storage.prototype.getItem = Storage.prototype.setItem = () => { throw new Error('Storage blocked'); }; });
  await blocked.goto(base + '/tai-khoan-chatgpt.html');
  await blocked.locator('.chapter-actions a').last().click();
  await blocked.waitForURL('**/thiet-lap-github.html');
  assert.equal(await blocked.locator('.reader-toolbar').count(), 1);
  await blocked.close();
  assert.deepEqual(errors, []);
  console.log('PASS: 21 focused lessons, TOC/Escape/focus, justified prose, native scroll, section alignment, shutter navigation/back and reduced motion');
})().catch(e => { console.error(e); process.exitCode = 1; }).finally(async () => { await browser?.close(); server.close(); });
